
# Лабораторна робота №10. Частина 2: Метод Адамса (прогноз-корекція)

# Імпортуємо бібліотеку numpy для зручної роботи з масивами чисел
import numpy as np
# Імпортуємо модуль pyplot для побудови графіків
import matplotlib.pyplot as plt

# =====================================================================
# ВВІДНІ ДАНІ (Тестова задача Коші)
# =====================================================================
# Рівняння: dy/dx = x + y
def f(x, y):
    return x + y

# Точний розв'язок для перевірки нашої похибки
def exact_solution(x):
    return 2 * np.exp(x) - x - 1

# Параметри відрізка та початкова умова (y(0) = 1)
a = 0.0
b = 2.0
y0 = 1.0

# Стандартний постійний крок
h_default = 0.01

# Метод Рунге-Кутта 4-го порядку.
# В методі Адамса він потрібен для "розгону" (знайти перші точки) 
# та для безпечної зміни кроку, щоб програма не зависала.
def rk4_step(x, y, h):
    k1 = f(x, y)
    k2 = f(x + h/2, y + h*k1/2)
    k3 = f(x + h/2, y + h*k2/2)
    k4 = f(x + h, y + h*k3)
    return y + (h / 6) * (k1 + 2*k2 + 2*k3 + k4)

# =====================================================================
# ПУНКТ 2: Метод прогнозу та корекції Адамса 2-го порядку (постійний крок)
# =====================================================================
def adams_method(a, b, y0, h):
    n = int((b - a) / h)
    x = np.linspace(a, b, n + 1)
    
    # Створюємо масив для результатів
    y = np.zeros(n + 1)
    y[0] = y0 # Перша точка задана умовою Коші
    
    # Знаходимо y[1] за допомогою методу Рунге-Кутта (це наш "розгін")
    if n > 0:
        y[1] = rk4_step(x[0], y[0], h)
        
    # Масив для збереження спрогнозованих значень (щоб потім оцінити похибку)
    y_pre_list = np.zeros(n + 1)
    
    # Основний цикл Адамса починається з i=1, бо y[0] і y[1] вже відомі
    for i in range(1, n):
        # 1. ЕТАП ПРОГНОЗУ (Екстраполяція)
        y_pre = y[i] + (h / 2) * (3 * f(x[i], y[i]) - f(x[i-1], y[i-1]))
        y_pre_list[i+1] = y_pre
        
        # 2. ЕТАП КОРЕКЦІЇ (Інтерполяція)
        y_cor = y_pre # Нульове наближення коректора - це наш прогноз
        
        # Робимо 2 ітерації коректора (згідно з методичкою)
        for _ in range(2):
            y_cor = y[i] + (h / 2) * (f(x[i+1], y_cor) + f(x[i], y[i]))
            
        y[i+1] = y_cor
        
    return x, y, y_pre_list

# =====================================================================
# ПУНКТ 5: Метод Адамса з автоматичним вибором кроку
# =====================================================================
def adams_auto_step(a, b, y0, eps=1e-4):
    # Використовуємо списки, бо кількість кроків динамічно змінюється
    x = [a]
    y = [y0]
    
    h = 0.05 # Початковий крок
    h_list = [h]
    
    # Робимо перший "розгінний" крок методом РК4
    x.append(a + h)
    y.append(rk4_step(a, y0, h))
    h_list.append(h)
    
    i = 1 # Індекс поточної точки
    
    # Умова b - x[-1] > 1e-9 захищає від мікроскопічних похибок округлення (float)
    while b - x[-1] > 1e-9:
        
        # Щоб випадково не перестрибнути кінець відрізка (точку b)
        if x[-1] + h > b:
            h = b - x[-1]
            x.append(x[-1] + h)
            y.append(rk4_step(x[-1], y[-1], h))
            h_list.append(h)
            break
            
        # 1. Прогноз (використовуємо 2 останні відомі точки)
        y_pre = y[i] + (h / 2) * (3 * f(x[i], y[i]) - f(x[i-1], y[i-1]))
        
        # 2. Корекція (робимо лише 1 ітерацію, щоб просто оцінити похибку)
        y_cor = y[i] + (h / 2) * (f(x[-1] + h, y_pre) + f(x[i], y[i]))
        
        # Оцінка похибки (П.4 методички)
        error = abs(y_cor - y_pre)
        
        # ЯКЩО ПОХИБКА ВЕЛИКА:
        if error > eps:
            h /= 2  # Зменшуємо крок
            # Щоб програма не зависала, ми не починаємо все з нуля, 
            # а просто робимо наступний крок з ПОТОЧНОЇ точки надійним методом РК4.
            next_y = rk4_step(x[i], y[i], h)
            x.append(x[i] + h)
            y.append(next_y)
            h_list.append(h)
            i += 1
            continue
            
        # ЯКЩО ПОХИБКА ДУЖЕ МАЛА:
        elif error < eps / 4:
            h *= 2  # Збільшуємо крок для економії часу
            # Знову ж таки, використовуємо РК4 для безпечного переходу на новий крок
            next_y = rk4_step(x[i], y[i], h)
            x.append(x[i] + h)
            y.append(next_y)
            h_list.append(h)
            i += 1
            continue
            
        # ЯКЩО КРОК ПІДХОДИТЬ (похибка в межах норми):
        # Робимо повноцінні 2 ітерації коректора для ідеальної точності
        for _ in range(2):
             y_cor = y[i] + (h / 2) * (f(x[i] + h, y_cor) + f(x[i], y[i]))
             
        # Зберігаємо успішний крок Адамса
        x.append(x[i] + h)
        y.append(y_cor)
        h_list.append(h)
        i += 1
        
    return np.array(x), np.array(y), np.array(h_list)

# =====================================================================
# ГОЛОВНИЙ БЛОК: Вивід у термінал та побудова графіків
# =====================================================================
if __name__ == "__main__":
    # --- ВИКОНАННЯ ОБЧИСЛЕНЬ ---
    
    # Рахуємо методом Адамса зі сталим кроком.
    x_adams, y_adams, y_pre_adams = adams_method(a, b, y0, h_default)
    
    # Точний розв'язок
    y_exact = exact_solution(x_adams)
    
    # Пункт 3: Рахуємо ТОЧНУ похибку (відхилення від аналітичного)
    error_exact = np.abs(y_adams - y_exact)
    
    # Пункт 4: Рахуємо ОЦІНОЧНУ похибку (різниця між корекцією і прогнозом)
    error_est = np.abs(y_adams - y_pre_adams)
    
    # Рахуємо з алгоритмом автоматичного кроку
    x_auto, y_auto, h_auto = adams_auto_step(a, b, y0)

    # --- ВИВІД У ТЕРМІНАЛ ---
    print("=" * 50)
    print("ЧАСТИНА 2: МЕТОД АДАМСА (ПРОГНОЗ-КОРЕКЦІЯ)")
    print("=" * 50)
    print(f"Сталий крок (h = {h_default}):")
    print(f"Максимальна точна похибка: {np.max(error_exact):.2e}")
    print(f"Максимальна оціночна похибка (y_cor - y_pre): {np.max(error_est):.2e}")
    print("-" * 50)
    print("Автоматичний вибір кроку:")
    print(f"Кількість обчислених точок: {len(x_auto)}")
    print(f"Мінімальний крок: {np.min(h_auto):.4f}")
    print(f"Максимальний крок: {np.max(h_auto):.4f}")
    print("=" * 50)

    # --- ПОБУДОВА ГРАФІКІВ ---
    plt.style.use('seaborn-v0_8-whitegrid')
    plt.figure(figsize=(12, 5))
    
    # Перший графік: Порівняння точної та оціночної похибок
    plt.subplot(1, 2, 1)
    plt.plot(x_adams, error_exact, color='red', label='Точна похибка (П.3)')
    # Малюємо оціночну похибку пунктиром, щоб було видно обидві лінії
    plt.plot(x_adams, error_est, '--', color='blue', label='Оцінка (П.4)')
    plt.title("Похибки методу Адамса")
    plt.xlabel("x")
    plt.ylabel("Похибка")
    plt.legend()
    
    # Другий графік: Зміна розміру кроку
    plt.subplot(1, 2, 2)
    # plt.step створює "сходинки" замість прямих ліній
    plt.step(x_auto, h_auto, color='purple', label='Крок h(x) (П.5)')
    plt.title("Автоматичний вибір кроку (Адамс)")
    plt.xlabel("x")
    plt.ylabel("Величина кроку")
    plt.legend()
    
    plt.tight_layout()
    plt.show()