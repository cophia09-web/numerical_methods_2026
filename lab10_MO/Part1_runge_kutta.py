
# Лабораторна робота №10. Частина 1: Метод Рунге-Кутта

# Імпортуємо бібліотеку numpy для зручної роботи з масивами чисел та математичними функціями
import numpy as np
# Імпортуємо модуль pyplot для побудови графіків
import matplotlib.pyplot as plt

# =====================================================================
# ВВІДНІ ДАНІ (Тестова задача Коші)
# =====================================================================
# Функція, що описує праву частину диференціального рівняння: dy/dx = f(x, y)
# У нашому випадку це dy/dx = x + y
def f(x, y):
    return x + y

# Точний (аналітичний) розв'язок цього рівняння. 
# Він потрібен нам виключно для того, щоб оцінити, наскільки помиляється наш чисельний метод.
def exact_solution(x):
    return 2 * np.exp(x) - x - 1

# Задаємо відрізок інтегрування [a, b]
a = 0.0  # Початкова точка відрізка
b = 2.0  # Кінцева точка відрізка

# Початкова умова задачі Коші: y(a) = y0. Тобто при x=0, y=1
y0 = 1.0

# Заданий постійний крок сітки (згідно з пунктом 6 методички)
h_default = 0.01  

# =====================================================================
# ДОПОМІЖНА ФУНКЦІЯ: Один крок методу Рунге-Кутта 4-го порядку
# =====================================================================
# Ця функція рахує значення y в наступній точці (x + h)
def rk4_step(x, y, h):
    # Обчислюємо 4 коефіцієнти (нахили дотичних у різних точках на кроці h)
    k1 = f(x, y)                                # Нахил на початку кроку
    k2 = f(x + h/2, y + h * k1 / 2)             # Нахил в середині кроку (за допомогою k1)
    k3 = f(x + h/2, y + h * k2 / 2)             # Ще один нахил в середині кроку (за допомогою k2)
    k4 = f(x + h, y + h * k3)                   # Нахил в кінці кроку (за допомогою k3)
    
    # Знаходимо наступне значення y, беручи зважену суму цих нахилів
    # Метод має 4-й порядок точності, тому ділимо на 6 (1+2+2+1 = 6)
    return y + (h / 6) * (k1 + 2*k2 + 2*k3 + k4)

# =====================================================================
# ПУНКТ 6: Метод Рунге-Кутта 4 зі заданим постійним кроком
# =====================================================================
def runge_kutta_4(a, b, y0, h):
    # Обчислюємо кількість кроків (відрізок ділимо на крок)
    n = int((b - a) / h)
    
    # Створюємо масив точок x: рівномірна сітка від a до b
    x = np.linspace(a, b, n + 1)
    
    # Створюємо масив для значень y, заповнюємо його нулями
    y = np.zeros(n + 1)
    
    # Встановлюємо початкову умову (перший елемент масиву)
    y[0] = y0
    
    # У циклі проходимо по всіх точках і рахуємо наступне значення y
    for i in range(n):
        y[i+1] = rk4_step(x[i], y[i], h)
        
    # Повертаємо масиви координат x та знайдених значень y
    return x, y

# =====================================================================
# ПУНКТ 9: Метод Рунге-Кутта з автоматичним вибором кроку
# =====================================================================
def runge_kutta_auto_step(a, b, y0, eps=1e-5):
    # Ініціалізуємо списки для збереження результатів (використовуємо списки, бо їх розмір заздалегідь невідомий)
    x = [a]
    y = [y0]
    h_list = []
    
    # Задаємо початковий крок (може бути достатньо великим)
    h = 0.1  
    
    # Змінні для відстеження поточної позиції
    curr_x = a
    curr_y = y0
    
    # Виконуємо обчислення, поки не дійдемо до кінця відрізка b
    while curr_x < b:
        # Щоб випадково не вийти за межі відрізка, на останньому кроці обрізаємо h
        if curr_x + h > b: 
            h = b - curr_x
            
        # 1. Робимо один великий крок величиною h
        y_h = rk4_step(curr_x, curr_y, h)
        
        # 2. Робимо два маленьких кроки величиною h/2
        y_half_1 = rk4_step(curr_x, curr_y, h/2)           # Перша половинка
        y_half_2 = rk4_step(curr_x + h/2, y_half_1, h/2)   # Друга половинка
        
        # ПУНКТ 8: Оцінка локальної похибки за правилом Рунге (формула з методички)
        # Різниця між значенням з повним кроком та двома половинними
        error = (16 / 15) * abs(y_half_2 - y_h)
        
        # Якщо похибка більша за задану точність (eps)
        if error > eps:
            h /= 2  # Крок завеликий, зменшуємо його вдвічі
            continue # Повертаємося на початок циклу, щоб перерахувати з новим кроком
        
        # Якщо ми дійшли сюди, значить крок підходить. Зберігаємо результати
        curr_x += h
        curr_y = y_half_2  # Беремо значення y_half_2, бо воно точніше (пораховане дрібнішим кроком)
        
        x.append(curr_x)
        y.append(curr_y)
        h_list.append(h)
        
        # Якщо похибка дуже-дуже маленька, ми можемо зекономити час і збільшити крок
        # Ділимо на 32, бо для методу 4-го порядку константа k = 2^(s+1) = 2^5 = 32
        if error < eps / 32:
            h *= 2  # Збільшуємо крок вдвічі для наступної ітерації
            
    # Перетворюємо списки у масиви numpy для зручної побудови графіків
    return np.array(x), np.array(y), np.array(h_list)

# =====================================================================
# ГОЛОВНИЙ БЛОК: Вивід результатів у термінал та побудова графіків
# =====================================================================
if __name__ == "__main__":
    # --- ВИКОНАННЯ ОБЧИСЛЕНЬ ---
    
    # Рахуємо методом Рунге-Кутта 4 зі сталим кроком
    x_rk4, y_rk4 = runge_kutta_4(a, b, y0, h_default)
    
    # Рахуємо точний розв'язок для тих самих точок x
    y_exact = exact_solution(x_rk4)
    
    # Знаходимо точну абсолютну похибку (модуль різниці між наближеним і точним значенням)
    error_exact = np.abs(y_rk4 - y_exact)
    
    # Рахуємо з алгоритмом автоматичного кроку
    x_auto, y_auto, h_auto = runge_kutta_auto_step(a, b, y0)

    # --- ВИВІД У ТЕРМІНАЛ ---
    print("=" * 50)
    print("ЧАСТИНА 1: МЕТОД РУНГЕ-КУТТА 4-ГО ПОРЯДКУ")
    print("=" * 50)
    print(f"Сталий крок (h = {h_default}):")
    # Виводимо максимальну похибку в експоненційному форматі (напр. 1.23e-10)
    print(f"Максимальна точна похибка: {np.max(error_exact):.2e}")
    print("-" * 50)
    print("Автоматичний вибір кроку:")
    print(f"Кількість обчислених точок: {len(x_auto)}")
    print(f"Мінімальний крок: {np.min(h_auto):.4f}")
    print(f"Максимальний крок: {np.max(h_auto):.4f}")
    print("=" * 50)

    # --- ПОБУДОВА ГРАФІКІВ ---
    # Задаємо гарний стиль для графіків
    plt.style.use('seaborn-v0_8-whitegrid')
    # Створюємо вікно для двох графіків поруч (розмір 12 на 5 дюймів)
    plt.figure(figsize=(12, 5))
    
    # Перший графік: Точна похибка
    plt.subplot(1, 2, 1) # 1 рядок, 2 колонки, 1-й графік
    plt.plot(x_rk4, error_exact, color='green', label='Точна похибка (П.7)')
    plt.title("Похибка методу Рунге-Кутта 4")
    plt.xlabel("x")
    plt.ylabel("Похибка")
    # Використовуємо логарифмічну шкалу по осі Y, оскільки похибка дуже стрімко росте, 
    # але залишається дуже малою (близько 10^-10)
    plt.yscale('log')
    plt.legend()
    
    # Другий графік: Зміна розміру кроку
    plt.subplot(1, 2, 2) # 1 рядок, 2 колонки, 2-й графік
    # Використовуємо plt.step для малювання сходинок, бо крок змінюється стрибками
    # Додаємо h_auto[0] на початок, щоб розмірність масивів збігалася з x_auto
    plt.step(x_auto, [h_auto[0]] + list(h_auto), color='orange', label='Крок h(x) (П.9)')
    plt.title("Автоматичний вибір кроку")
    plt.xlabel("x")
    plt.ylabel("Величина кроку")
    plt.legend()
    
    # Автоматично вирівнюємо відступи між графіками
    plt.tight_layout()
    # Показуємо вікно з графіками
    plt.show()